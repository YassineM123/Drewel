function formatMap(obj) {
  let res = '{\n';
  for (const [k, v] of Object.entries(obj)) {
    const escapedK = k.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
    const escapedV = v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
    res += `        '${escapedK}': '${escapedV}',\n`;
  }
  res += '      }';
  return res;
}

